def is_disposable_domain(domain: str) -> bool:
    """
    Check if a domain is a known disposable email provider.

    Args:
        domain: The email domain to check (e.g., 'mailinator.com')

    Returns:
        True if the domain is a known disposable email provider
    """
    if not domain:
        return False
    return domain.lower().strip() in DISPOSABLE_DOMAINS


def get_disposable_domains() -> frozenset[str]:
    """
    Get the complete set of disposable domains.

    Returns:
        Frozen set of all known disposable email domains
    """
    return DISPOSABLE_DOMAINS


def get_disposable_domain_count() -> int:
    """
    Get the count of known disposable domains.

    Returns:
        Number of domains in the disposable list
    """
    return len(DISPOSABLE_DOMAINS)
